use std::env;
use std::error::Error;
use std::fs;
use std::io;
use std::path::PathBuf;

use tauri_build::{AppManifest, Attributes};

const APP_COMMANDS: &[&str] = &[
    "app_info",
    "app_limits",
    "open_image_dialog",
    "save_image_dialog",
    "release_handle",
    "import_source",
    "import_demo",
    "start_preview",
    "export_file",
    "cancel",
    "reset",
    "set_menu_state",
];
const SMOKE_COMMANDS: &[&str] = &[
    "app_info",
    "app_limits",
    "open_image_dialog",
    "save_image_dialog",
    "release_handle",
    "import_source",
    "import_demo",
    "start_preview",
    "export_file",
    "cancel",
    "reset",
    "set_menu_state",
    "echo_binary",
    "smoke_page",
    "smoke_worker_probe",
    "smoke_queue_open",
    "smoke_queue_save",
    "smoke_e2e",
    "smoke_menu_action",
    "smoke_menu_snapshot",
];
/// Permission files generated only for smoke commands. Removing them keeps a default build's
/// ACL free of smoke identifiers, because stale gitignored files would otherwise be embedded.
const SMOKE_PERMISSION_FILES: &[&str] = &[
    "echo_binary",
    "smoke_page",
    "smoke_worker_probe",
    "smoke_queue_open",
    "smoke_queue_save",
    "smoke_e2e",
    "smoke_menu_action",
    "smoke_menu_snapshot",
];

fn main() -> Result<(), Box<dyn Error>> {
    let smoke = env::var_os("CARGO_FEATURE_SMOKE").is_some();
    let (commands, capabilities) = if smoke {
        (SMOKE_COMMANDS, "./capabilities/*.json")
    } else {
        remove_stale_smoke_permissions()?;
        (APP_COMMANDS, "./capabilities/app.json")
    };
    println!(
        "cargo:rustc-env=IMAGE_TO_BINARY_TARGET={}",
        env::var("TARGET")?
    );
    tauri_build::try_build(
        Attributes::new()
            .app_manifest(AppManifest::new().commands(commands))
            .capabilities_path_pattern(capabilities),
    )?;
    Ok(())
}

/// Deletes exactly the smoke-only generated permission files, ignoring any that are absent.
fn remove_stale_smoke_permissions() -> io::Result<()> {
    let root =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").ok_or_else(|| {
            io::Error::new(io::ErrorKind::NotFound, "CARGO_MANIFEST_DIR is not set")
        })?);
    let generated = root.join("permissions").join("autogenerated");
    for command in SMOKE_PERMISSION_FILES {
        match fs::remove_file(generated.join(format!("{command}.toml"))) {
            Ok(()) => {}
            Err(error) if error.kind() == io::ErrorKind::NotFound => {}
            Err(error) => return Err(error),
        }
    }
    Ok(())
}
